"""Draw the keyboard and mouse button prompts: runtime/prompt_icons_art.h.

    python tools/make_prompt_icons.py [--font <bold .ttf>] [--preview out.png]

runtime/prompt_icons.c shows these in place of the game's controller button icons while keyboard and mouse are the
device used last. Each is a 64x64 coverage mask in the game's own style (a white shape with the label cut out, which the
game tints), drawn here: a key cap with its label, or a mouse with the pressed button. Each comes as two masks, the shape
and the part cut out of it: a one-channel icon of the game takes the shape less the cut, a two-channel one (a disc in
one channel, its label cut out of the other) takes them apart. The runtime scales the masks to the box of the icon it
replaces. Nothing here comes from the game. The labels are set in DejaVu Sans Bold (Bitstream Vera
licence, THIRD_PARTY_NOTICES.md); the default path is where Debian and MSYS2 install it.
"""
import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'runtime' / 'prompt_icons_art.h'
S = 256            # drawn at 4x, then reduced to 64x64 for smooth edges
SIZE = 64
FONTS = ['/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 'C:/msys64/usr/share/fonts/TTF/DejaVuSans-Bold.ttf',
         'C:/Windows/Fonts/DejaVuSans-Bold.ttf']


def key_cap(label, font_path, size=150):
    """A rounded key cap filling the icon (shape) and its label (cut)."""
    shape, cut = Image.new('L', (S, S), 0), Image.new('L', (S, S), 0)
    ImageDraw.Draw(shape).rounded_rectangle((10, 10, S - 10, S - 10), radius=52, fill=255)
    d = ImageDraw.Draw(cut)
    if label == 'SPACE':   # the space bar's symbol: an open bracket under the baseline
        d.line((64, 120, 64, 160, 192, 160, 192, 120), fill=255, width=24, joint='curve')
        return shape, cut
    font = ImageFont.truetype(font_path, size)
    box = d.textbbox((0, 0), label, font=font)
    w, h = box[2] - box[0], box[3] - box[1]
    d.text(((S - w) / 2 - box[0], (S - h) / 2 - box[1]), label, font=font, fill=255)
    return shape, cut


def mouse(button):
    """A mouse seen from above: its body (shape), and cut out of it its inside but for the outline, the buttons' seams
    and the button used ('L', 'R', 'M'), or with arrows either side for its motion."""
    shape, keep = Image.new('L', (S, S), 0), Image.new('L', (S, S), 0)
    body = (60, 14, S - 60, S - 14)
    split = 108   # the buttons' lower edge
    mid = S // 2
    ImageDraw.Draw(shape).rounded_rectangle(body, radius=66, fill=255)
    d = ImageDraw.Draw(keep)   # what stays lit inside the body
    d.rounded_rectangle(body, radius=66, fill=255)
    d.rounded_rectangle((body[0] + 16, body[1] + 16, body[2] - 16, body[3] - 16), radius=52, fill=0)
    d.line((body[0] + 8, split, body[2] - 8, split), fill=255, width=16)
    d.line((mid, body[1] + 8, mid, split), fill=255, width=16)
    if button == 'L':
        d.rounded_rectangle((body[0] + 8, body[1] + 8, mid, split), radius=50, fill=255)
        d.rectangle((mid - 30, body[1] + 8, mid, split), fill=255)
        d.rectangle((body[0] + 8, split - 40, mid, split), fill=255)
    elif button == 'R':
        d.rounded_rectangle((mid, body[1] + 8, body[2] - 8, split), radius=50, fill=255)
        d.rectangle((mid, body[1] + 8, mid + 30, split), fill=255)
        d.rectangle((mid, split - 40, body[2] - 8, split), fill=255)
    elif button == 'M':
        d.rounded_rectangle((mid - 18, body[1] + 30, mid + 18, split - 22), radius=18, fill=255)
    elif button == 'MOVE':   # arrows either side: the camera
        for x, sg in ((26, 1), (S - 26, -1)):
            for img in (shape, keep):
                ImageDraw.Draw(img).polygon(((x, mid + 20), (x + 26 * sg, mid - 6), (x + 26 * sg, mid + 46)), fill=255)
    cut = Image.eval(keep, lambda v: 255 - v)
    return shape, Image.composite(cut, Image.new('L', (S, S), 0), shape)


def icons(font):
    return {
        'KEY_E': key_cap('E', font), 'KEY_Q': key_cap('Q', font), 'KEY_R': key_cap('R', font),
        'KEY_M': key_cap('M', font), 'KEY_Z': key_cap('Z', font), 'KEY_C': key_cap('C', font),
        'KEY_TAB': key_cap('Tab', font, 100), 'KEY_SPACE': key_cap('SPACE', font), 'KEY_SHIFT': key_cap('Shift', font, 64),
        'MOUSE_L': mouse('L'), 'MOUSE_R': mouse('R'), 'MOUSE_M': mouse('M'), 'MOUSE_MOVE': mouse('MOVE'),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--font', help='DejaVu Sans Bold (DejaVuSans-Bold.ttf)')
    ap.add_argument('--preview', type=Path, help='also write a contact sheet of the icons to this PNG')
    a = ap.parse_args()
    font = a.font or next((f for f in FONTS if Path(f).is_file()), None)
    if not font:
        sys.exit('DejaVuSans-Bold.ttf not found: pass --font')
    art = {k: tuple(m.resize((SIZE, SIZE), Image.LANCZOS) for m in v) for k, v in icons(font).items()}
    lines = ['// Generated by tools/make_prompt_icons.py: keyboard and mouse button prompts, 64x64 coverage masks drawn',
             '// for this port (labels in DejaVu Sans Bold, THIRD_PARTY_NOTICES.md). runtime/prompt_icons.c scales them.',
             '// [art][0] is the shape, [art][1] the part cut out of it.',
             '#pragma once', '#include <stdint.h>', '',
             f'enum {{ PROMPT_ART_SIZE = {SIZE} }};', 'enum PromptArt {']
    lines += [f'    PROMPT_{k},' for k in art] + ['    PROMPT_ART_COUNT', '};', '',
                                                  'static const uint8_t prompt_art[PROMPT_ART_COUNT][2][64 * 64] = {']
    for k, masks in art.items():
        lines.append(f'    [PROMPT_{k}] = {{')
        for im in masks:
            px = im.tobytes()
            lines.append('        {')
            for r in range(SIZE):
                lines.append('            ' + ','.join(str(v) for v in px[r * SIZE:(r + 1) * SIZE]) + ',')
            lines.append('        },')
        lines.append('    },')
    lines += ['};', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{OUT.relative_to(ROOT)}: {len(art)} icons')
    if a.preview:
        sheet = Image.new('L', ((SIZE + 8) * len(art), SIZE + 8), 60)
        for i, (shape, cut) in enumerate(art.values()):
            sheet.paste(Image.composite(Image.new('L', shape.size, 0), shape, cut), (4 + i * (SIZE + 8), 4))
        sheet.save(a.preview)


if __name__ == '__main__':
    main()
